// Formato obligatorio de commits y PRs (CONTRIBUTING.md). Cada caso es un error que un
// commit real podría tener; el mensaje de error tiene que decir qué corregir.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { validateMessage, validatePullRequest } from '../../scripts/commit-msg/validate.js';

const VALID = `fix(orders): canonizar la escala de amount en el hash

Problema:
amount 100 y "100.00" daban hashes distintos: el reintento recibía 422.

Valor para el negocio:
Un reintento legítimo no se rechaza.

Solución:
- Decimal2 devuelve el monto con dos decimales.

Cómo se probó:
- automático: pnpm test:unit (commit-msg, orders); falló antes del cambio
- manual: n/a

Refs: #4`;

const without = (section: string) =>
  VALID.split('\n\n').filter((block) => !block.startsWith(section)).join('\n\n');

describe('validateMessage', () => {
  it('acepta el formato completo', () => {
    expect(validateMessage(VALID)).toEqual([]);
  });

  it('acepta CRLF, comentarios de git, comentarios HTML y trailers al final', () => {
    const msg = `${VALID}\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nClaude-Session: https://claude.ai/x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_x\n# Please enter the commit message`;
    expect(validateMessage(`<!-- plantilla -->\n${msg}`.replace(/\n/g, '\r\n'))).toEqual([]);
  });

  it('acepta varias refs y título sin alcance', () => {
    expect(validateMessage(VALID.replace('fix(orders):', 'chore:').replace('Refs: #4', 'Refs: #4, #12'))).toEqual([]);
  });

  it.each([
    ['tipo fuera de la lista', VALID.replace('fix(orders)', 'bugfix(orders)'), 'título inválido'],
    ['título en mayúsculas sin tipo', VALID.replace(/^.*$/m, 'Arreglo el hash'), 'título inválido'],
    ['alcance con mayúsculas', VALID.replace('(orders)', '(Orders)'), 'título inválido'],
    ['título de más de 72', VALID.replace(/^.*$/m, `fix: ${'a'.repeat(70)}`), 'máximo 72'],
    ['título con punto final', VALID.replace(/^(.*)$/m, '$1.'), 'no termina en punto'],
  ])('rechaza %s', (_, msg, expected) => {
    expect(validateMessage(msg).join('\n')).toContain(expected);
  });

  it('exige la línea en blanco después del título', () => {
    expect(validateMessage(VALID.replace('\n\nProblema:', '\nProblema:'))).toContain('la segunda línea debe estar en blanco');
  });

  it.each(['Problema:', 'Valor para el negocio:', 'Solución:', 'Cómo se probó:'])('exige la sección %s', (s) => {
    expect(validateMessage(without(s))).toContain(`falta la sección "${s}"`);
  });

  it('exige Refs con número de issue', () => {
    expect(validateMessage(without('Refs:'))).toContain('falta la línea "Refs: #<issue>"');
    expect(validateMessage(VALID.replace('Refs: #4', 'Refs: issue 4')).join('\n')).toContain('Refs inválido');
  });

  it('exige el orden de las secciones', () => {
    const blocks = VALID.split('\n\n');
    [blocks[1], blocks[2]] = [blocks[2], blocks[1]];
    expect(validateMessage(blocks.join('\n\n')).join('\n')).toContain('en este orden');
  });

  it('rechaza una sección vacía', () => {
    expect(validateMessage(VALID.replace('Un reintento legítimo no se rechaza.\n', '')))
      .toContain('la sección "Valor para el negocio:" está vacía');
  });

  it('exige un ítem en Solución y las dos líneas de Cómo se probó', () => {
    expect(validateMessage(VALID.replace('- Decimal2', 'Decimal2'))).toContain('"Solución:" necesita al menos un ítem "- …"');
    expect(validateMessage(VALID.replace('- manual: n/a\n', '')).join('\n')).toContain('"- manual: …"');
    expect(validateMessage(VALID.replace(/- automático: .*\n/, '')).join('\n')).toContain('"- automático: …"');
  });

  it('rechaza texto libre después de Refs', () => {
    expect(validateMessage(`${VALID}\n\notra cosa`).join('\n')).toContain('sobra: "otra cosa"');
  });

  it('acepta un pie libre separado por "---" (el que GitHub guardó en el PR #8)', () => {
    const footer = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_x)_';
    expect(validateMessage(VALID + footer)).toEqual([]);
    // El texto libre antes del separador sigue rechazado.
    expect(validateMessage(`${VALID}\n\notra cosa${footer}`).join('\n')).toContain('sobra: "otra cosa"');
  });
});

describe('validatePullRequest', () => {
  const [title, ...rest] = VALID.split('\n');
  const body = rest.slice(1).join('\n');

  it('acepta título y descripción válidos', () => {
    expect(validatePullRequest(title, body)).toEqual([]);
  });

  it('valida el título real aunque empiece con "#": la descripción no lo reemplaza', () => {
    // La descripción es un mensaje completo válido: antes, "#..." se descartaba como comentario
    // de git y la primera línea de la descripción pasaba por título.
    expect(validatePullRequest('# título inválido', VALID).join('\n')).toContain('título inválido: "# título inválido"');
  });

  it('rechaza un título vacío', () => {
    expect(validatePullRequest('', body).join('\n')).toContain('título inválido: ""');
  });
});

describe('check.ts (CLI)', () => {
  const ROOT = resolve(import.meta.dirname, '../..');
  const GIT_ENV = {
    GIT_AUTHOR_NAME: 'test', GIT_AUTHOR_EMAIL: 'test@example.com',
    GIT_COMMITTER_NAME: 'test', GIT_COMMITTER_EMAIL: 'test@example.com',
  };
  let dir: string;

  const cli = (args: string[], env: Record<string, string> = {}) => {
    const r = spawnSync(join(ROOT, 'node_modules/.bin/tsx'), [join(ROOT, 'scripts/commit-msg/check.ts'), ...args],
      { cwd: dir, encoding: 'utf8', env: { ...process.env, ...GIT_ENV, ...env } });
    return { code: r.status, out: r.stdout + r.stderr };
  };
  const git = (...args: string[]) => {
    const r = spawnSync('git', args, { cwd: dir, encoding: 'utf8', env: { ...process.env, ...GIT_ENV } });
    if (r.status !== 0) throw new Error(r.stderr);
    return r.stdout.trim();
  };
  const commit = (message: string) => git('commit', '-q', '--allow-empty', '-m', message);

  beforeAll(() => {
    dir = mkdtempSync(join(tmpdir(), 'commit-msg-'));
    git('init', '-q', '-b', 'main');
    commit('base');
  });
  afterAll(() => rmSync(dir, { recursive: true, force: true }));

  it('--file: 0 con un mensaje válido, 1 con uno inválido y dice qué corregir', () => {
    writeFileSync(join(dir, 'ok'), VALID);
    writeFileSync(join(dir, 'bad'), without('Problema:'));
    expect(cli(['--file', join(dir, 'ok')])).toMatchObject({ code: 0, out: expect.stringContaining('✓ formato correcto') });
    const bad = cli(['--file', join(dir, 'bad')]);
    expect(bad.code).toBe(1);
    expect(bad.out).toContain('falta la sección "Problema:"');
  });

  it('--range: un commit inválido seguido de uno válido sigue fallando', () => {
    const base = git('rev-parse', 'HEAD');
    commit(VALID.replace('fix(orders)', 'bugfix(orders)'));
    const invalid = git('rev-parse', '--short=7', 'HEAD');
    commit(VALID);
    const r = cli(['--range', `${base}..HEAD`]);
    expect(r.code).toBe(1);
    expect(r.out).toContain(`✗ commit ${invalid}`);
    expect(r.out).toContain('título inválido');
  });

  it('--range: rechaza un commit de merge', () => {
    const base = git('rev-parse', 'HEAD');
    // Mensajes distintos: con el mismo padre, árbol y segundo, dos commits iguales serían uno.
    git('checkout', '-q', '-b', 'lado');
    commit(VALID.replace('Refs: #4', 'Refs: #5'));
    git('checkout', '-q', 'main');
    commit(VALID.replace('Refs: #4', 'Refs: #6'));
    git('merge', '-q', '--no-ff', '-m', VALID, 'lado');
    const r = cli(['--range', `${base}..HEAD`]);
    expect(r.code).toBe(1);
    expect(r.out).toContain('commit de merge');
  });

  it('--range: un rango sin commits falla', () => {
    expect(cli(['--range', 'HEAD..HEAD'])).toMatchObject({ code: 1, out: expect.stringContaining('sin commits en HEAD..HEAD') });
  });

  it('--pr: valida PR_TITLE como título, aunque PR_BODY sea un mensaje completo válido', () => {
    const [title, ...rest] = VALID.split('\n');
    expect(cli(['--pr'], { PR_TITLE: title, PR_BODY: rest.slice(1).join('\n') }).code).toBe(0);
    const r = cli(['--pr'], { PR_TITLE: '# título inválido', PR_BODY: VALID });
    expect(r.code).toBe(1);
    expect(r.out).toContain('título inválido: "# título inválido"');
  });

  it('sin modo: muestra el uso y sale con 1', () => {
    expect(cli([])).toMatchObject({ code: 1, out: expect.stringContaining('uso: check.ts') });
  });
});
